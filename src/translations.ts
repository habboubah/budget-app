const translations = { de, en } satisfies Record<string, Strings>;
export default translations;

export type Language = keyof typeof translations;
export const languages = Object.keys(translations) as Language[];
export const isLanguage = (v: unknown): v is Language =>
  typeof v === 'string' && (languages as string[]).includes(v);
export const DEFAULT_LANGUAGE: Language = 'de';

/** Fill `{name}` placeholders. */
export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Pick the singular or plural string and fill in `{n}`. */
export function plural(n: number, one: string, many: string, vars: Record<string, string | number> = {}): string {
  return fmt(n === 1 ? one : many, { n, ...vars });
}
